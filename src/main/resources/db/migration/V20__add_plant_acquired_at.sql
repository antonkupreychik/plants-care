-- V20__add_plant_acquired_at.sql
-- Issue #117: «дни рождения» растений и UI архива.
--
-- Добавляем дату, когда юзер «завёл» растение. Используется для:
--   * шедулера годовщин (раз в год шлём «у %name% годовщина»);
--   * строки «С тобой с …» в карточке растения / архиве.
--
-- Backward-compat note:
--   * Колонка NULLABLE без DEFAULT — старый код, не знающий о ней,
--     продолжает писать в plants без проблем; существующие строки
--     получают NULL и просто не участвуют в годовщинах.
--   * Никакого бэкфилла — по issue решено, что для уже заведённых
--     растений acquired_at юзер проставит руками при желании.
--   * Безопасно для rolling deploy: миграцию можно применить до
--     раскатки новой версии приложения.
--
-- Индекс по acquired_at намеренно НЕ создаётся здесь: запрос шедулера
-- годовщин — это пара условий (acquired_at IS NOT NULL AND archived_at IS NULL),
-- частичный индекс под него создаётся в V21 вместе с таблицей идемпотентности.

BEGIN;

ALTER TABLE plants
    ADD COLUMN acquired_at DATE;

COMMENT ON COLUMN plants.acquired_at IS
    'Дата, когда юзер завёл растение. Используется для годовщин и строки '
        '«С тобой с …». NULL = юзер не указал, в годовщинах не участвует.';

COMMIT;
