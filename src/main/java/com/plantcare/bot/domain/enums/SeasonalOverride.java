package com.plantcare.bot.domain.enums;

/**
 * Per-plant решение по поводу сезонности (issue #67).
 *
 * <ul>
 *   <li>{@link #INHERIT} — следовать глобальной настройке юзера. Дефолт для всех
 *       новых растений: ровно тот случай, для которого глобальная настройка
 *       и придумана.</li>
 *   <li>{@link #ON} — сезонность включена для этого растения, даже если у юзера
 *       глобально выключена. Полезно для конкретных «привередливых» растений.</li>
 *   <li>{@link #OFF} — сезонность не применяется к этому растению, даже если у
 *       юзера глобально включена. Полезно для растений без выраженной сезонности
 *       (например, кактусов).</li>
 * </ul>
 */
public enum SeasonalOverride {
    INHERIT,
    ON,
    OFF
}
