package com.plantcare.core.domain.enums;

/**
 * Исход одной попытки доставки уведомления (issue #95).
 *
 * <p>Статуса {@code DELIVERED} нет намеренно: ни Telegram Bot API, ни FCM не
 * возвращают подтверждение фактической доставки на устройство — оба отвечают
 * «принято провайдером». Заводить статус, который никто никогда не проставит,
 * значит рисовать в дашборде вечный ноль.
 */
public enum DeliveryStatus {

    /** Сообщение принято провайдером канала. */
    SENT,

    /** Провайдер отверг отправку (403/400, протухший push-токен, сетевая ошибка). */
    FAILED,

    /** Провайдер ответил 429 — превышен лимит запросов. */
    RATE_LIMITED;

    /** Любой статус, кроме {@link #SENT}, считается ошибкой доставки. */
    public boolean isFailure() {
        return this != SENT;
    }
}
