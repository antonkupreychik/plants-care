package com.plantcare.core.domain.enums;

/**
 * Тип события в журнале растения (issue #76).
 *
 * <p>Это редкие, разовые события (не регулярный уход): пересадка, обрезка,
 * обработка от вредителей и пр. Регулярные задачи живут в {@link TaskType}.
 *
 * <p>В отличие от {@code TaskType}, у событий нет расписания и нет адаптивных
 * рекомендаций — это просто факты на временной шкале для контекста.
 */
public enum PlantEventType {

    /** Пересадка / смена горшка. */
    TRANSPLANT,

    /** Замена грунта / досыпка. */
    SOIL_CHANGE,

    /** Обрезка (формирующая, санитарная, корней). */
    PRUNING,

    /** Обработка от вредителей / болезней. */
    PEST_TREATMENT
}
